const fs = require('node:fs');
const path = require('node:path');
const { promisify } = require('node:util');
const execFile = promisify(require('node:child_process').execFile);
const root = path.resolve(__dirname, '../..');
const selections = [
    ['Pushups.gif', 'push-up', ['Push Up', 'Push-ups']],
    ['Squats 01.gif', 'bodyweight-squat', ['Bodyweight Squat']],
    ['Situps.gif', 'sit-up', ['Sit Up', 'Sit-ups']],
    ['Legraises.gif', 'lying-leg-raise', ['Lying Leg Raises', 'Lying Leg Raise']],
    ['Jumpingrope.gif', 'jump-rope', ['Jump Rope', 'Rope Jumping']],
    ['Pullup.gif', 'pull-up', ['Pull Up', 'Pull-ups']],
];
const normalize = value => value.toLowerCase().replace(/[^a-z0-9]/g, '');
const plainText = value => (value || '').replace(/<[^>]+>/g, '').trim();
async function json(url) {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: ${response.status}`);
    return response.json();
}
async function main() {
    const photos = process.argv[2] ? JSON.parse(fs.readFileSync(process.argv[2], 'utf8')).photos
        : await json('https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json');
    const dataDir = path.join(root, 'mobile/src/data');
    const mediaDir = path.join(root, 'mobile/assets/exercise-demos');
    fs.mkdirSync(mediaDir, { recursive: true });
    const photoIndex = {};
    for (const exercise of photos) if (exercise.images?.length) photoIndex[normalize(exercise.name)] = exercise.images;
    fs.writeFileSync(path.join(dataDir, 'exercisePhotos.json'), JSON.stringify(photoIndex, null, 2) + '\n');
    const query = new URLSearchParams({ action: 'query', format: 'json', prop: 'imageinfo', iiprop: 'url|extmetadata',
        titles: selections.map(([file]) => 'File:' + file).join('|') });
    const metadata = await json('https://commons.wikimedia.org/w/api.php?' + query);
    const records = [];
    for (const [filename, slug, names] of selections) {
        const info = Object.values(metadata.query.pages).find(item => item.title === 'File:' + filename)?.imageinfo?.[0];
        if (!info) throw new Error('Missing media metadata: ' + filename);
        const license = info.extmetadata.LicenseShortName?.value;
        if (!/^CC (BY(?:-SA)?|0)/.test(license || '')) throw new Error('Unreviewed license: ' + license);
        const sourceUrl = info.url.split('?')[0];
        const output = path.join(mediaDir, slug + '.gif');
        if (!fs.existsSync(output)) {
            const response = await fetch(sourceUrl);
            if (!response.ok) throw new Error('GIF ' + filename + ': ' + response.status);
            fs.writeFileSync(output, Buffer.from(await response.arrayBuffer()));
        }
        const probe = await execFile('ffprobe', ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=nb_frames', '-of', 'csv=p=0', output]);
        if (Number(probe.stdout.trim()) < 2) throw new Error('Not animated: ' + filename);
        await execFile('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-i', output, '-frames:v', '1', path.join(mediaDir, slug + '.jpg')]);
        records.push({ slug, names, author: plainText(info.extmetadata.Artist?.value), license,
            licenseUrl: info.extmetadata.LicenseUrl?.value, sourceUrl, sourcePageUrl: info.descriptionurl,
            changes: 'Original GIF unchanged. A still poster was extracted for reduced motion and paused playback.' });
        console.log(slug, 'frames', probe.stdout.trim(), Math.round(fs.statSync(output).size / 1024) + ' KB');
    }
    fs.writeFileSync(path.join(mediaDir, 'SOURCES.json'), JSON.stringify({ retrieved: new Date().toISOString().slice(0, 10), records }, null, 2) + '\n');
    const imports = records.map((r, i) => `    { ...sources.records[${i}], animation: Asset.fromModule(require('../../assets/exercise-demos/${r.slug}.gif')).uri, poster: Asset.fromModule(require('../../assets/exercise-demos/${r.slug}.jpg')).uri },`).join('\n');
    fs.writeFileSync(path.join(dataDir, 'exerciseAnimations.ts'), `// Generated by backend/scripts/build_open_exercise_media.cjs\nimport { Asset } from 'expo-asset';\nimport sources from '../../assets/exercise-demos/SOURCES.json';\nexport const exerciseAnimations = [\n${imports}\n];\n`);
    console.log('Photo names', Object.keys(photoIndex).length, 'animations', records.length);
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
