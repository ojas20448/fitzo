// Bundle the existing exact-match catalog photos so workouts do not depend on a remote image host.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const ts = require(path.join(root, 'mobile/node_modules/typescript'));
const source = fs.readFileSync(path.join(root, 'mobile/src/data/defaultExercises.ts'), 'utf8');
const exportsValue = {};
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: exportsValue });
const prefix = 'https://pieyjxokfjvsnfygblmv.supabase.co/storage/v1/object/public/exercise-images/';
const directory = path.join(root, 'mobile/assets/exercise-photos');
async function main() {
    fs.mkdirSync(directory, { recursive: true });
    const selected = [...new Map(exportsValue.defaultExercises.filter(item => item.gifUrl?.startsWith(prefix)).map(item => [item.id, item])).values()];
    const records = [];
    // Small batches avoid overwhelming the public source host.
    for (let index = 0; index < selected.length; index += 6) {
        const batch = await Promise.all(selected.slice(index, index + 6).map(async exercise => {
            assert.match(exercise.id, /^[a-z0-9_]+$/);
            const file = exercise.gifUrl.slice(prefix.length).split(/[?#]/)[0];
            const url = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/' + file;
            const output = path.join(directory, exercise.id + '.jpg');
            let bytes = fs.existsSync(output) ? fs.readFileSync(output) : null;
            if (!bytes) {
                const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
                assert(response.ok, `${exercise.id}: HTTP ${response.status}`);
                assert(response.headers.get('content-type')?.startsWith('image/'), `${exercise.id}: not an image`);
                bytes = Buffer.from(await response.arrayBuffer());
            }
            assert(bytes.length > 200 && bytes.length < 1000000, `${exercise.id}: unexpected image size`);
            assert(bytes[0] === 0xff && bytes[1] === 0xd8, `${exercise.id}: not JPEG`);
            fs.writeFileSync(output, bytes);
            return { id: exercise.id, name: exercise.name, sourceUrl: url, file: exercise.id + '.jpg', sha256: crypto.createHash('sha256').update(bytes).digest('hex'), bytes: bytes.length };
        }));
        records.push(...batch);
    }
    assert(records.length > 100, 'Expected the existing built-in photo catalog');
    const instructionsSource = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json';
    const response = await fetch(instructionsSource, { signal: AbortSignal.timeout(30000) });
    assert(response.ok, 'Could not load the matching source instructions');
    const catalog = await response.json();
    const bySourceId = new Map(catalog.map(item => [item.id, item.instructions]));
    const guides = {};
    for (const record of records) {
        const sourceId = decodeURIComponent(new URL(record.sourceUrl).pathname.split('/').at(-2));
        const instructions = bySourceId.get(sourceId);
        if (Array.isArray(instructions) && instructions.length && instructions.every(step => typeof step === 'string')) guides[record.id] = instructions;
    }
    assert(Object.keys(guides).length > 100, 'Expected exact-source guides for the bundled photos');
    fs.writeFileSync(path.join(root, 'mobile/src/data/exerciseTechniqueGuides.json'), JSON.stringify(guides, null, 2) + '\n');
    fs.writeFileSync(path.join(directory, 'SOURCES.json'), JSON.stringify({ source: 'https://github.com/yuhonas/free-exercise-db', license: 'Unlicense', licenseUrl: 'https://github.com/yuhonas/free-exercise-db/blob/main/LICENSE.md', instructionsSource, changes: 'Original JPEGs and source instructions unchanged.', records }, null, 2) + '\n');
    fs.writeFileSync(path.join(root, 'mobile/src/data/exerciseStaticPhotos.ts'), '// Generated by backend/scripts/bundle_workout_photos.cjs\nimport { Asset } from \'expo-asset\';\nexport const exerciseStaticPhotos: Record<string, string> = {\n' + records.map(record => `    '${record.id}': Asset.fromModule(require('../../assets/exercise-photos/${record.file}')).uri,`).join('\n') + '\n};\n');
    console.log(JSON.stringify({ photos: records.length, guides: Object.keys(guides).length, bytes: records.reduce((sum, item) => sum + item.bytes, 0) }));
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
